/**
 * API client for glucose prediction.
 * Calls Claude AI with structured prompt and parses JSON response.
 */
import { sendChatMessage, MODEL_SONNET } from '@features/hints/utils/aiClient';
import { sanitizeRecommendation } from '@features/analyzer/engine/safetyGuard';
import { buildPredictionSystemPrompt } from '../data/predictionSystemPrompt';
import type { PredictionDataSnapshot, PredictionResult } from '../data/predictionTypes';

/**
 * Sends prediction data to Claude and parses the structured JSON response.
 * Throws on API errors or malformed responses.
 */
export async function requestPrediction(
  snapshot: PredictionDataSnapshot
): Promise<PredictionResult> {
  const systemPrompt = buildPredictionSystemPrompt(snapshot);

  const rawResponse = await sendChatMessage(
    systemPrompt,
    [{ role: 'user', content: 'Analyze the data and provide the prediction JSON.' }],
    { maxTokens: 2048, timeoutMs: 60_000, model: MODEL_SONNET }
  );

  return parsePredictionResponse(rawResponse);
}

/**
 * Parses AI response text into PredictionResult.
 * Handles common issues: markdown code fences, trailing text, etc.
 */
function parsePredictionResponse(raw: string): PredictionResult {
  // Strip markdown code fences if present
  let cleaned = raw.trim();
  if (cleaned.startsWith('```json')) {
    cleaned = cleaned.slice(7);
  } else if (cleaned.startsWith('```')) {
    cleaned = cleaned.slice(3);
  }
  if (cleaned.endsWith('```')) {
    cleaned = cleaned.slice(0, -3);
  }
  cleaned = cleaned.trim();

  // Try to find JSON object boundaries
  const firstBrace = cleaned.indexOf('{');
  const lastBrace = cleaned.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    cleaned = cleaned.slice(firstBrace, lastBrace + 1);
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(cleaned);
  } catch {
    // Fallback: return error result
    return createErrorResult('Failed to parse AI response');
  }

  // Validate required fields
  if (!parsed || typeof parsed !== 'object') {
    return createErrorResult('Invalid response format');
  }

  const result = parsed as Record<string, unknown>;

  // Ensure required fields exist with defaults
  const predictionResult: PredictionResult = {
    status: validateStatus(result.status) ? result.status : 'error',
    predictions: Array.isArray(result.predictions) ? result.predictions : [],
    checklist: Array.isArray(result.checklist) ? result.checklist : [],
    summary: typeof result.summary === 'string' ? result.summary : '',
    remission:
      result.remission && typeof result.remission === 'object'
        ? (result.remission as PredictionResult['remission'])
        : undefined,
    disclaimer: typeof result.disclaimer === 'string' ? result.disclaimer : getDefaultDisclaimer(),
    generatedAt:
      typeof result.generatedAt === 'string' ? result.generatedAt : new Date().toISOString(),
    expiresAt:
      typeof result.expiresAt === 'string'
        ? result.expiresAt
        : new Date(Date.now() + 6 * 60 * 60 * 1000).toISOString(),
  };

  return sanitizePredictionResult(predictionResult);
}

/**
 * M002: every user-facing text field of the AI response must pass the same
 * safety guard as local analyzer output — the prompt forbids dose advice,
 * but prompts are not a guarantee. Runs before caching, so a violating
 * response can't be re-shown from cache either.
 */
function sanitizePredictionResult(result: PredictionResult): PredictionResult {
  const clean = (text: string): string => sanitizeRecommendation(text).sanitizedText;
  return {
    ...result,
    summary: clean(result.summary),
    disclaimer: clean(result.disclaimer),
    checklist: result.checklist.map(item => ({
      ...item,
      title: typeof item.title === 'string' ? clean(item.title) : item.title,
      description:
        typeof item.description === 'string' ? clean(item.description) : item.description,
      timing: typeof item.timing === 'string' ? clean(item.timing) : item.timing,
    })),
    remission: result.remission
      ? {
          ...result.remission,
          summary:
            typeof result.remission.summary === 'string'
              ? clean(result.remission.summary)
              : result.remission.summary,
          factors: Array.isArray(result.remission.factors)
            ? result.remission.factors.map(f => (typeof f === 'string' ? clean(f) : f))
            : result.remission.factors,
        }
      : undefined,
  };
}

function validateStatus(status: unknown): status is PredictionResult['status'] {
  return status === 'success' || status === 'insufficient_data' || status === 'error';
}

function getDefaultDisclaimer(): string {
  return "This analysis is generated by AI and is not a substitute for professional veterinary advice. Always consult your veterinarian before making any changes to your pet's treatment plan.";
}

function createErrorResult(message: string): PredictionResult {
  return {
    status: 'error',
    predictions: [],
    checklist: [],
    summary: message,
    disclaimer: getDefaultDisclaimer(),
    generatedAt: new Date().toISOString(),
    expiresAt: new Date(Date.now() + 6 * 60 * 60 * 1000).toISOString(),
  };
}
